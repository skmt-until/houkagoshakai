export function regionSlug(name: string): string {
  return REGION_SLUGS[name] ?? name;
}

export function prefSlug(name: string): string {
  return PREF_SLUGS[name] ?? name;
}

export function regionByslug(slug: string): RegionGroup | undefined {
  return regions.find((r) => regionSlug(r.name) === slug);
}

export function prefByRegionAndSlug(regionSlugStr: string, prefSlugStr: string): Prefecture | undefined {
  const region = regionByslug(regionSlugStr);
  return region?.prefs.find((p) => prefSlug(p.name) === prefSlugStr);
}

